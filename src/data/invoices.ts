const shipmentRoutes = seedInvoices.map(({ route, truckId }) => ({ route, truckId: truckId ?? "" }));

export const invoices: Invoice[] = seedInvoices.map((invoice, index) => {
  const transactionCount = 2 + (index % 3);
  const totalAmount = Math.round(invoice.amount * transactionCount * 100) / 100;
  const issueDate = new Date(`${invoice.issueDate}T00:00:00`);
  const servicePeriodEnd = new Date(issueDate);
  servicePeriodEnd.setDate(servicePeriodEnd.getDate() - 1);
  const servicePeriodStart = new Date(servicePeriodEnd);
  servicePeriodStart.setDate(servicePeriodStart.getDate() - 6);
  const transactionAmount = Math.floor((totalAmount / transactionCount) * 100) / 100;
  const transactions = Array.from({ length: transactionCount }, (_, transactionIndex) => {
    const shipment = shipmentRoutes[(index + transactionIndex * 7) % shipmentRoutes.length];
    const transactionDate = new Date(servicePeriodStart);
    transactionDate.setDate(transactionDate.getDate() + Math.floor((transactionIndex * 7) / transactionCount));

    return {
      id: `${invoice.id}_txn_${transactionIndex + 1}`,
      truckId: shipment.truckId,
      route: shipment.route,
      date: toIsoDate(transactionDate),
      amount:
        transactionIndex === transactionCount - 1
          ? Math.round((totalAmount - transactionAmount * (transactionCount - 1)) * 100) / 100
          : transactionAmount,
    };
  });
  const paidDate = new Date(issueDate);
  paidDate.setDate(paidDate.getDate() + 1);

  return {
    ...invoice,
    truckId: null,
    route: `${transactionCount} shipments across multiple routes`,
    amount: totalAmount,
    status: index < 3 ? "pending" : "paid",
    paidAt: index < 3 ? null : invoice.paidAt ?? toIsoDate(paidDate),
    servicePeriodStart: toIsoDate(servicePeriodStart),
    servicePeriodEnd: toIsoDate(servicePeriodEnd),
    transactions,
  };
});
